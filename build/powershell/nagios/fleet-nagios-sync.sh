#!/bin/bash
# fleet-nagios-sync - mirror the fleet server's enrolled hosts into Nagios.
#
# Polls GET /api/hosts on an NSClient fleet server and renders one Nagios cfg
# file per enrolled host (a passive host object plus one passive service per
# entry in the services list). When the rendered tree differs from the live one
# the live tree is swapped out, validated with `nagios4 -v`, and Nagios is
# reloaded - a validation failure rolls the previous tree back, so a bad render
# can never take the monitoring server down. A fleet server that does not answer
# leaves the config untouched: hosts are only removed when the server says so.
#
# Installed by setup-nagios-machine.ps1 together with a systemd timer; the
# config below normally comes from /etc/fleet-nagios-sync.conf (root:root 0600,
# it holds the API key). A view_only fleet API key is all this needs.
#
# Test mode (no fleet server, no root, no Nagios):
#   fleet-nagios-sync.sh --hosts-file hosts.json --render-only out-dir/
set -u

CONF_FILE="${FLEET_NAGIOS_SYNC_CONF:-/etc/fleet-nagios-sync.conf}"

# Defaults (Ubuntu nagios4 layout), overridable from the environment and, with
# higher precedence, from the conf file.
FLEET_SERVER="${FLEET_SERVER:-}"
FLEET_API_KEY="${FLEET_API_KEY:-}"
CURL_OPTS="${CURL_OPTS:-}"
NAGIOS_CFG="${NAGIOS_CFG:-/etc/nagios4/nagios.cfg}"
FLEET_CONF_DIR="${FLEET_CONF_DIR:-/etc/nagios4/conf.d/fleet}"
SERVICES_LIST="${SERVICES_LIST:-/etc/nagios4/fleet-services.list}"
NAGIOS_BIN="${NAGIOS_BIN:-nagios4}"
RELOAD_CMD="${RELOAD_CMD:-systemctl reload nagios4}"

HOSTS_FILE=""
RENDER_ONLY=""
while [ $# -gt 0 ]; do
    case "$1" in
        --hosts-file)  HOSTS_FILE="$2"; shift 2 ;;
        --render-only) RENDER_ONLY="$2"; shift 2 ;;
        *) echo "fleet-nagios-sync: unknown argument: $1" >&2; exit 2 ;;
    esac
done

if [ -r "$CONF_FILE" ]; then
    # shellcheck source=/dev/null
    . "$CONF_FILE"
fi

fail() { echo "fleet-nagios-sync: $*" >&2; exit 1; }

command -v jq >/dev/null 2>&1 || fail "jq is required"
[ -r "$SERVICES_LIST" ] || fail "services list $SERVICES_LIST is missing"

# --- fetch ------------------------------------------------------------------
if [ -n "$HOSTS_FILE" ]; then
    hosts_json=$(cat "$HOSTS_FILE") || fail "cannot read $HOSTS_FILE"
else
    [ -n "$FLEET_SERVER" ] || fail "FLEET_SERVER is not set (edit $CONF_FILE)"
    [ -n "$FLEET_API_KEY" ] || fail "FLEET_API_KEY is not set (edit $CONF_FILE)"
    # shellcheck disable=SC2086  # CURL_OPTS is intentionally word-split
    hosts_json=$(curl -fsS --max-time 30 $CURL_OPTS \
        -H "Authorization: Bearer $FLEET_API_KEY" \
        "${FLEET_SERVER%/}/api/hosts") \
        || fail "could not fetch ${FLEET_SERVER%/}/api/hosts - keeping the current Nagios config"
fi

echo "$hosts_json" | jq -e 'type == "array"' >/dev/null 2>&1 \
    || fail "the fleet server did not return a host array - keeping the current Nagios config"

# --- render -----------------------------------------------------------------
# Enrolled hosts only: a row that never enrolled (a pending "Add host") has no
# agent, so putting it in Nagios would only produce a permanently stale host.
# enrolled_at is how the server itself defines "enrolled", so unlike a status
# vocabulary it cannot drift. hostname\tid\tos, tab-separated.
enrolled=$(echo "$hosts_json" | jq -r '
    .[]
    | select(.hostname != null and .enrolled_at != null)
    | [.hostname, .id, (.os // "unknown")] | @tsv')

tmp_dir=$(mktemp -d) || fail "mktemp failed"
trap 'rm -rf "$tmp_dir"' EXIT
render_dir="$tmp_dir/fleet"
mkdir -p "$render_dir"

count=0
while IFS=$'\t' read -r hostname host_id host_os; do
    [ -n "$hostname" ] || continue
    # The hostname becomes a file name and a Nagios object name; anything
    # outside this alphabet is either malice or breakage - skip it loudly.
    case "$hostname" in
        (*[!A-Za-z0-9._-]*|.*|-*)
            echo "fleet-nagios-sync: skipping host with unsafe hostname: $hostname (fleet id $host_id)" >&2
            continue ;;
    esac
    {
        echo "# Generated by fleet-nagios-sync - DO NOT EDIT (fleet id $host_id, os $host_os)"
        echo "define host {"
        echo "    use        fleet-host"
        echo "    host_name  $hostname"
        echo "    address    $hostname"
        echo "}"
        while IFS= read -r service; do
            [ -n "$service" ] || continue
            case "$service" in \#*) continue ;; esac
            echo ""
            echo "define service {"
            echo "    use                 fleet-passive-service"
            echo "    host_name           $hostname"
            echo "    service_description $service"
            echo "}"
        done < "$SERVICES_LIST"
    } > "$render_dir/$hostname.cfg"
    count=$((count + 1))
done <<EOF
$enrolled
EOF

if [ -n "$RENDER_ONLY" ]; then
    mkdir -p "$RENDER_ONLY"
    rm -rf "${RENDER_ONLY:?}"/*.cfg
    cp "$render_dir"/*.cfg "$RENDER_ONLY"/ 2>/dev/null
    echo "fleet-nagios-sync: rendered $count host(s) into $RENDER_ONLY"
    exit 0
fi

# --- swap + validate + reload ------------------------------------------------
# One writer at a time: the timer and a hand-run (or the provisioning script)
# must not interleave their rm/cp/validate steps on the live tree.
lock_file="${LOCK_FILE:-/run/lock/fleet-nagios-sync.lock}"
if command -v flock >/dev/null 2>&1; then
    exec 9>"$lock_file" || fail "cannot open lock $lock_file"
    flock -w 120 9 || fail "another fleet-nagios-sync is still running"
fi

mkdir -p "$FLEET_CONF_DIR"
if diff -r -q "$FLEET_CONF_DIR" "$render_dir" >/dev/null 2>&1; then
    echo "fleet-nagios-sync: no change ($count host(s))"
    exit 0
fi

# Whole-directory copies ("dir/." works for an empty tree too), and the
# previous tree goes back whenever anything after this point fails: the live
# directory must never be left empty on disk, or the next nagios restart dies.
backup_dir="$tmp_dir/previous"
cp -a "$FLEET_CONF_DIR" "$backup_dir" || fail "could not back up $FLEET_CONF_DIR"
restore_previous() {
    rm -rf "${FLEET_CONF_DIR:?}"/*.cfg
    cp -a "$backup_dir"/. "$FLEET_CONF_DIR"/ || echo "fleet-nagios-sync: RESTORE FAILED - $FLEET_CONF_DIR may be incomplete" >&2
}
rm -rf "${FLEET_CONF_DIR:?}"/*.cfg
if ! cp -a "$render_dir"/. "$FLEET_CONF_DIR"/; then
    restore_previous
    fail "could not write into $FLEET_CONF_DIR - restored the previous tree"
fi

# Capture the validation output before rolling back - re-running it afterwards
# would validate the restored (good) tree and report nothing useful.
if ! validate_out=$("$NAGIOS_BIN" -v "$NAGIOS_CFG" 2>&1); then
    echo "$validate_out" >&2
    restore_previous
    fail "the rendered config failed nagios validation - rolled back"
fi

$RELOAD_CMD || fail "nagios reload failed"
echo "fleet-nagios-sync: applied $count host(s) and reloaded nagios"
