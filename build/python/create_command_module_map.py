"""Write the command -> module map the core uses to explain an unknown command.

Reads the module.json of every module this build produces (the folders are
passed on the command line) and writes a header listing, for each command they
register, the module that provides it. When a query names a command no loaded
module has, the core looks it up here to say which module to enable.

Only built modules are listed, so a command whose module does not exist on this
platform (check_eventlog on Linux) gets no hint. Commands registered at runtime
(scripts, aliases, external scripts) are absent by nature.
"""
import os
from optparse import OptionParser

from module_json import load_module_json, command_names


def cstring(value):
	return '"%s"' % value.replace('\\', '\\\\').replace('"', '\\"')


def render(entries):
	lines = [
		'// Generated by build/python/create_command_module_map.py from the module.json',
		'// of every module this build produces. Do not edit.',
		'#pragma once',
		'',
		'namespace nsclient {',
		'namespace core {',
		'namespace generated {',
		'',
		'struct command_module_entry {',
		'  const char *command;',
		'  const char *module;',
		'};',
		'',
		'// Sorted by command (lower case, as the command registry keys them); a',
		'// command more than one module provides is listed once per module. Ends',
		'// with a null entry so a build without modules still has an array.',
		'static const command_module_entry command_module_map[] = {',
	]
	for command, module in entries:
		lines.append('    {%s, %s},' % (cstring(command), cstring(module)))
	lines += [
		'    {nullptr, nullptr},',
		'};',
		'',
		'}  // namespace generated',
		'}  // namespace core',
		'}  // namespace nsclient',
		'',
	]
	return '\n'.join(lines)


def main():
	parser = OptionParser(usage='%prog --target FILE MODULE_FOLDER...')
	parser.add_option('-t', '--target', help='header FILE to write', metavar='FILE')
	(options, folders) = parser.parse_args()
	if not options.target:
		parser.error('--target is required')

	entries = set()
	for folder in folders:
		if not os.path.isfile(os.path.join(folder, 'module.json')):
			continue
		data = load_module_json(folder)
		module = (data.get('module') or {}).get('name')
		if not module:
			continue
		for command in command_names(data):
			entries.add((command.lower(), module))

	content = render(sorted(entries)).encode('utf-8')
	# Leave an unchanged header alone, so re-running CMake does not rebuild
	# the core.
	if os.path.exists(options.target):
		with open(options.target, 'rb') as f:
			if f.read() == content:
				return
	os.makedirs(os.path.dirname(os.path.abspath(options.target)), exist_ok=True)
	with open(options.target, 'wb') as f:
		f.write(content)


if __name__ == '__main__':
	main()
