/**
 * `nscp icinga-agent import` — take over the identity of the Icinga 2 agent
 * on the host: its key, its certificate and the Icinga CA into the
 * certificate directory, and the same parent into /settings/Icinga/agent.
 *
 * Runs the CLI against a scratch INI and a made-up Icinga data directory laid
 * out the way the agent's own is; no master is involved. What is worth
 * pinning is what the command refuses: an identity it would have to guess,
 * and one that would not work once copied.
 */
import * as fs from "fs";
import * as path from "path";
import {
  NscpInstance,
  generateCertChain,
  iniValue,
  itOnUnix,
  type CertBundle,
} from "@fixtures/index";

jest.setTimeout(120_000);

const AGENT = "WIN-Host-01.example.com";
const PARENT = "icinga-master.example.com";
const SECTION = "/settings/Icinga/agent";

// zones.conf as `icinga2 node wizard` writes it on an agent.
const ZONES = `/*
 * Generated by Icinga 2 node setup commands
 */
object Endpoint "${PARENT}" {
	host = "192.0.2.10"
	port = "5665"
}
object Zone "master" {
	endpoints = [ "${PARENT}" ]
}
object Endpoint NodeName {
}
object Zone ZoneName {
	endpoints = [ NodeName ]
	parent = "master"
}
`;

describe("nscp icinga-agent import", () => {
  let nscp: NscpInstance;
  let pki: CertBundle;
  let icinga: string;
  let certs: string;
  let etc: string;
  let target: string;

  const setting = (key: string) => iniValue(nscp.settingsFile, SECTION, key);

  /** A fresh Icinga data directory holding the agent's files. */
  function icingaTree(name: string): string {
    const root = nscp.scratch(name);
    certs = path.join(root, "var", "lib", "icinga2", "certs");
    etc = path.join(root, "etc", "icinga2");
    fs.mkdirSync(certs, { recursive: true });
    fs.mkdirSync(etc, { recursive: true });
    fs.writeFileSync(path.join(certs, `${AGENT}.crt`), pki.signed.agent.certPem);
    fs.writeFileSync(path.join(certs, `${AGENT}.key`), pki.signed.agent.keyPem);
    fs.writeFileSync(path.join(certs, "ca.crt"), pki.ca.certPem);
    fs.writeFileSync(path.join(etc, "constants.conf"), `const NodeName = "${AGENT}"\n`);
    fs.writeFileSync(path.join(etc, "zones.conf"), ZONES);
    return root;
  }

  /** An import that is expected to be refused: a non-zero exit, not a throw. */
  const refused = (from: string) =>
    nscp.run(["icinga-agent", "import", "--from", from], { allowFailure: true });

  beforeAll(() => {
    nscp = new NscpInstance();
    pki = generateCertChain({
      outDir: nscp.scratch("pki"),
      caCommonName: "Icinga CA",
      signed: {
        agent: { commonName: AGENT },
        other: { commonName: "someone-else" },
      },
    });
    target = path.join(nscp.workDir, "security", "icinga");
  });

  beforeEach(() => {
    icinga = icingaTree(`icinga-${Date.now()}-${Math.random().toString(16).slice(2)}`);
  });

  it("shows what it would do and changes nothing with --dry-run", async () => {
    const r = await nscp.run(["icinga-agent", "import", "--from", icinga, "--dry-run"]);
    expect(r.all).toContain(`Would import the Icinga 2 agent '${AGENT}'`);
    expect(r.all).toContain(`Parent: ${PARENT} at 192.0.2.10:5665`);
    expect(fs.existsSync(target)).toBe(false);
    expect(setting("parent host")).toBeUndefined();
  });

  it("refuses a certificate that is not for the key beside it", async () => {
    fs.writeFileSync(path.join(certs, `${AGENT}.key`), pki.signed.other.keyPem);
    const r = await refused(icinga);
    expect(r.all).toContain("do not belong together");
    expect(fs.existsSync(path.join(target, `${AGENT}.key`))).toBe(false);
    expect(setting("parent host")).toBeUndefined();
  });

  it("refuses a certificate for another name", async () => {
    fs.writeFileSync(path.join(certs, `${AGENT}.crt`), pki.signed.other.certPem);
    fs.writeFileSync(path.join(certs, `${AGENT}.key`), pki.signed.other.keyPem);
    const r = await refused(icinga);
    expect(r.all).toContain("is for 'someone-else'");
    expect(fs.existsSync(path.join(target, `${AGENT}.key`))).toBe(false);
  });

  it("asks which parent when the agent has two", async () => {
    fs.appendFileSync(
      path.join(etc, "zones.conf"),
      `object Endpoint "icinga-master-2.example.com" { host = "192.0.2.11" }\n`,
    );
    const r = await refused(icinga);
    expect(r.all).toContain("has 2 parents");
    expect(r.all).toContain("--parent-endpoint");
    expect(fs.existsSync(path.join(target, `${AGENT}.key`))).toBe(false);
  });

  it("asks for the address when the parent connected to the agent", async () => {
    fs.writeFileSync(
      path.join(etc, "zones.conf"),
      `object Endpoint "${PARENT}" { }\nobject Endpoint NodeName { }\n`,
    );
    const r = await refused(icinga);
    expect(r.all).toContain("--parent-host");
    expect(fs.existsSync(path.join(target, `${AGENT}.key`))).toBe(false);
  });

  it("imports the identity and points the agent at the same parent", async () => {
    const r = await nscp.run(["icinga-agent", "import", "--from", icinga]);
    expect(r.all).toContain(`Imported the Icinga 2 agent '${AGENT}'`);
    expect(fs.readFileSync(path.join(target, `${AGENT}.key`), "utf8")).toBe(
      pki.signed.agent.keyPem,
    );
    expect(fs.readFileSync(path.join(target, `${AGENT}.crt`), "utf8")).toBe(
      pki.signed.agent.certPem,
    );
    expect(fs.readFileSync(path.join(target, "ca.crt"), "utf8")).toBe(pki.ca.certPem);
    // The name keeps its capitals: it selects the files and has to match the
    // Endpoint object on the master.
    expect(setting("endpoint name")).toBe(AGENT);
    expect(setting("parent endpoint")).toBe(PARENT);
    expect(setting("parent host")).toBe("192.0.2.10");
    expect(setting("parent port")).toBe("5665");
    expect(setting("trust on first use")).toBe("false");
    expect(iniValue(nscp.settingsFile, "/modules", "IcingaAgent")).toBe("enabled");
  });

  itOnUnix("stores the key readable by its owner only", () => {
    const mode = fs.statSync(path.join(target, `${AGENT}.key`)).mode & 0o777;
    expect(mode & 0o077).toBe(0);
  });

  it("is repeatable, and takes the name from the key when NodeName is not set", async () => {
    // The wizard leaves NodeName commented out when it is the host's FQDN.
    fs.writeFileSync(path.join(etc, "constants.conf"), `//const NodeName = "localhost"\n`);
    const r = await nscp.run([
      "icinga-agent",
      "import",
      "--from",
      icinga,
      "--parent-host",
      "master.example.com",
    ]);
    expect(r.all).toContain(`Imported the Icinga 2 agent '${AGENT}'`);
    expect(setting("parent host")).toBe("master.example.com");
  });

  it("does not replace a different identity unless told to", async () => {
    // A second agent's files under the same name: another key.
    const again = generateCertChain({
      outDir: nscp.scratch("pki-2"),
      caCommonName: "Icinga CA",
      signed: { agent: { commonName: AGENT } },
    });
    fs.writeFileSync(path.join(certs, `${AGENT}.crt`), again.signed.agent.certPem);
    fs.writeFileSync(path.join(certs, `${AGENT}.key`), again.signed.agent.keyPem);
    fs.writeFileSync(path.join(certs, "ca.crt"), again.ca.certPem);

    const r = await refused(icinga);
    expect(r.exitCode).not.toBe(0);
    expect(r.all).toContain("already a different key");
    expect(fs.readFileSync(path.join(target, `${AGENT}.key`), "utf8")).toBe(
      pki.signed.agent.keyPem,
    );

    const forced = await nscp.run(["icinga-agent", "import", "--from", icinga, "--force"]);
    expect(forced.all).toContain("Imported");
    expect(fs.readFileSync(path.join(target, `${AGENT}.key`), "utf8")).toBe(
      again.signed.agent.keyPem,
    );
    expect(fs.readFileSync(path.join(target, "ca.crt"), "utf8")).toBe(again.ca.certPem);
  });
});
